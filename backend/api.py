@app.get("/api/quizzes/{quiz_id}")
def get_quiz(quiz_id: int, user: dict = Depends(verified_telegram_user)):
    with closing(get_connection()) as conn:
        metadata = quiz_metadata(conn, quiz_id, user["id"])
        rows = owned_questions(conn, quiz_id, user["id"])
        return {
            **metadata,
            "questions": [
                {"id": row["id"], "text": row["question_text"],
                 "options": json.loads(row["options_json"])}
                for row in rows
            ],
        }


@app.post("/api/quizzes/{quiz_id}/submit")
def submit_quiz(
    quiz_id: int, body: Submission,
    user: dict = Depends(verified_telegram_user),
):
    # Normalize ordering so a reordered retry is still the same submission.
    fingerprint = hashlib.sha256(json.dumps(
        {"quiz_id": quiz_id, "answers": sorted(
            (answer.question_id, answer.option) for answer in body.answers
        )}, separators=(",", ":"),
    ).encode()).hexdigest()
    submission_id = str(body.submission_id)

    with closing(get_connection()) as conn, conn:
        # Serializes concurrent retries; attempt, answers and receipt commit together.
        conn.execute("BEGIN IMMEDIATE")
        previous = conn.execute(
            """SELECT request_hash, result_json FROM quiz_submissions
               WHERE telegram_user_id=? AND submission_id=?""",
            (user["id"], submission_id),
        ).fetchone()
        if previous:
            if previous["request_hash"] != fingerprint:
                raise HTTPException(409, "This submission ID was already used with different answers.")
            return json.loads(previous["result_json"])

        metadata = quiz_metadata(conn, quiz_id, user["id"])
        rows = owned_questions(conn, quiz_id, user["id"])
        answers = {answer.question_id: answer.option for answer in body.answers}
        if not rows or len(answers) != len(body.answers) or set(answers) != {r["id"] for r in rows}:
            raise HTTPException(400, "Answer every question exactly once.")
        for row in rows:
            if answers[row["id"]] not in {o["id"] for o in json.loads(row["options_json"])}:
                raise HTTPException(400, "Choose a valid option for every question.")

        correct = sum(answers[r["id"]] == r["correct_answer"] for r in rows)
        score = round(correct / len(rows) * 100, 1)
        cursor = conn.execute(
            """INSERT INTO quiz_attempts
               (quiz_id, telegram_user_id, status, score, completed_at)
               VALUES (?, ?, 'completed', ?, CURRENT_TIMESTAMP)""",
            (quiz_id, user["id"], score),
        )
        attempt_id = cursor.lastrowid
        feedback = []
        for row in rows:
            is_correct = answers[row["id"]] == row["correct_answer"]
            conn.execute(
                """INSERT INTO quiz_answers (attempt_id, question_id, answer, is_correct)
                   VALUES (?, ?, ?, ?)""",
                (attempt_id, row["id"], answers[row["id"]], int(is_correct)),
            )
            feedback.append({
                "question_id": row["id"], "text": row["question_text"],
                "options": json.loads(row["options_json"]),
                "selected_option": answers[row["id"]], "correct": is_correct,
                "correct_option": row["correct_answer"], "explanation": row["explanation"],
            })
        completed_at = conn.execute(
            "SELECT completed_at FROM quiz_attempts WHERE id=?", (attempt_id,),
        ).fetchone()[0]
        result = {
            "attempt_id": attempt_id, "quiz_id": quiz_id, "title": metadata["title"],
            "course_name": metadata["course_name"], "demo": metadata["demo"],
            "completed_at": completed_at, "score": score, "correct": correct,
            "total": len(rows), "feedback": feedback,
        }
        conn.execute(
            """INSERT INTO quiz_submissions
               (telegram_user_id, submission_id, quiz_id, request_hash, attempt_id, result_json)
               VALUES (?, ?, ?, ?, ?, ?)""",
            (user["id"], submission_id, quiz_id, fingerprint, attempt_id, json.dumps(result)),
        )
        return result


@app.get("/api/grades")
def list_grades(
    user: dict = Depends(verified_telegram_user),
    offset: Annotated[int, Query(ge=0)] = 0,
    limit: Annotated[int, Query(ge=1, le=100)] = 30,
):
    with closing(get_connection()) as conn:
        rows = conn.execute(
            """SELECT a.id, a.quiz_id, a.score, a.completed_at, e.exam_title,
                      e.course_name, e.source_reference='demo-mcq-v1' AS demo
               FROM quiz_attempts a
               JOIN quizzes q ON q.id=a.quiz_id JOIN exams e ON e.id=q.exam_id
               WHERE a.telegram_user_id=? AND e.telegram_user_id=? AND a.status='completed'
               ORDER BY a.id DESC LIMIT ? OFFSET ?""",
            (user["id"], user["id"], limit, offset),
        ).fetchall()
        return [{**dict(row), "demo": bool(row["demo"])} for row in rows]


@app.get("/api/attempts/{attempt_id}")
def get_attempt(attempt_id: int, user: dict = Depends(verified_telegram_user)):
    with closing(get_connection()) as conn:
        attempt = conn.execute(
            """SELECT a.*, e.exam_title, e.course_name,
                      e.source_reference='demo-mcq-v1' AS demo
               FROM quiz_attempts a JOIN quizzes q ON q.id=a.quiz_id
               JOIN exams e ON e.id=q.exam_id
               WHERE a.id=? AND a.telegram_user_id=? AND e.telegram_user_id=?
                 AND a.status='completed'""",
            (attempt_id, user["id"], user["id"]),
        ).fetchone()
        if not attempt:
            raise HTTPException(404, "Attempt not found")
        saved = conn.execute(
            "SELECT result_json FROM quiz_submissions WHERE attempt_id=? AND telegram_user_id=?",
            (attempt_id, user["id"]),
        ).fetchone()
        if saved:
            return json.loads(saved[0])
        # Preserve access to attempts completed before submission snapshots existed.
        rows = conn.execute(
            """SELECT q.*, a.answer, a.is_correct FROM quiz_answers a
               JOIN questions q ON q.id=a.question_id WHERE a.attempt_id=? ORDER BY q.id""",
            (attempt_id,),
        ).fetchall()
        feedback = [{
            "question_id": r["id"], "text": r["question_text"],
            "options": json.loads(r["options_json"]), "selected_option": r["answer"],
            "correct": bool(r["is_correct"]), "correct_option": r["correct_answer"],
            "explanation": r["explanation"],
        } for r in rows]
        return {
            "attempt_id": attempt_id, "quiz_id": attempt["quiz_id"],
            "title": attempt["exam_title"], "course_name": attempt["course_name"],
            "demo": bool(attempt["demo"]), "completed_at": attempt["completed_at"],
            "score": attempt["score"], "correct": sum(r["correct"] for r in feedback),
            "total": len(feedback), "feedback": feedback,
        }


