@app.get("/api/me")
def get_me(user: dict = Depends(verified_telegram_user)):
    with closing(get_connection()) as conn, conn:
        conn.execute("INSERT OR IGNORE INTO users (telegram_user_id) VALUES (?)", (user["id"],))
        stats = conn.execute(
            """SELECT COUNT(*) AS completed, MAX(score) AS best_score,
                      ROUND(AVG(score), 1) AS average_score
               FROM quiz_attempts WHERE telegram_user_id=? AND status='completed'""",
            (user["id"],),
        ).fetchone()
    return {**user, "stats": dict(stats)}


def quiz_metadata(conn, quiz_id, user_id):
    row = conn.execute(
        """SELECT q.id, e.exam_title AS title, e.course_name,
                  e.source_reference='demo-mcq-v1' AS demo,
                  (SELECT COUNT(*) FROM questions WHERE quiz_id=q.id) AS question_count
           FROM quizzes q JOIN exams e ON e.id=q.exam_id
           WHERE q.id=? AND e.telegram_user_id=?""",
        (quiz_id, user_id),
    ).fetchone()
    if not row:
        raise HTTPException(404, "Quiz not found")
    return {**dict(row), "demo": bool(row["demo"])}


