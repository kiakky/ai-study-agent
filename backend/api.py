def verified_telegram_user(
    x_telegram_init_data: Annotated[
        str | None, Header()
    ] = None,
) -> dict:
    """Validate signed Telegram Mini App identity."""

    if not BOT_TOKEN or not x_telegram_init_data or len(x_telegram_init_data) > 16384:
        raise HTTPException(
            status_code=401,
            detail="Open the Mini App inside Telegram.",
        )

    try:
        pairs = parse_qsl(
            x_telegram_init_data,
            keep_blank_values=True,
            strict_parsing=True,
        )

        data = dict(pairs)

        if len(pairs) != len(data):
            raise ValueError("Duplicate authentication field")

        received_hash = data.pop("hash")

        # Bot-token HMAC covers every received field except hash, including
        # signature when present (distinct from third-party Ed25519 validation).

        check_string = "\n".join(
            f"{key}={value}"
            for key, value in sorted(data.items())
        )

        secret = hmac.new(
            b"WebAppData",
            BOT_TOKEN.encode(),
            hashlib.sha256,
        ).digest()

        expected_hash = hmac.new(
            secret,
            check_string.encode(),
            hashlib.sha256,
        ).hexdigest()

        if not hmac.compare_digest(
            received_hash,
            expected_hash,
        ):
            raise ValueError("Invalid signature")

        age = time.time() - int(data["auth_date"])

        if age < -60 or age > 24 * 3600:
            raise ValueError("Expired authentication")

        user = json.loads(data["user"])
        if not isinstance(user, dict) or type(user.get("id")) is not int:
            raise ValueError("Invalid user")
        user_id = user["id"]

        if not 0 < user_id <= 2**63 - 1:
            raise ValueError("Invalid user")

        return {
            "id": user_id,
            "first_name": user.get("first_name", "Student"),
        }

    except (KeyError, ValueError, TypeError):
        raise HTTPException(
            status_code=401,
            detail="Invalid or expired Telegram authentication.",
        ) from None


def ensure_demo_quiz(user_id: int) -> int:
    """Create one sample MCQ quiz per Telegram student."""

    with closing(get_connection()) as conn, conn:
        conn.execute("BEGIN IMMEDIATE")

        conn.execute(
            """
            INSERT OR IGNORE INTO users (telegram_user_id)
            VALUES (?)
            """,
            (user_id,),
        )

        exam = conn.execute(
            """
            SELECT id FROM exams
            WHERE telegram_user_id=?
              AND source_reference='demo-mcq-v1'
            LIMIT 1
            """,
            (user_id,),
        ).fetchone()

        if exam:
            exam_id = exam["id"]
        else:
            cursor = conn.execute(
                """
                INSERT INTO exams
                    (telegram_user_id, course_name,
                     exam_title, source_reference)
                VALUES (?, ?, ?, ?)
                """,
                (
                    user_id,
                    "Demo Course",
                    "Sample MCQ Practice",
                    "demo-mcq-v1",
                ),
            )
            exam_id = cursor.lastrowid

        existing_quiz = conn.execute(
            """
            SELECT id FROM quizzes
            WHERE exam_id=?
            ORDER BY id
            LIMIT 1
            """,
            (exam_id,),
        ).fetchone()

        if existing_quiz:
            return existing_quiz["id"]

        cursor = conn.execute(
            "INSERT INTO quizzes (exam_id) VALUES (?)",
            (exam_id,),
        )

        quiz_id = cursor.lastrowid

        for question, choices, correct, explanation in DEMO_QUESTIONS:
            options = [
                {"id": letter, "text": text}
                for letter, text in zip("ABCD", choices)
            ]

            conn.execute(
                """
                INSERT INTO questions
                    (quiz_id, question_text, question_type,
                     options_json, correct_answer, explanation)
                VALUES (?, ?, 'mcq', ?, ?, ?)
                """,
                (
                    quiz_id,
                    question,
                    json.dumps(options),
                    correct,
                    explanation,
                ),
            )

        return quiz_id


def owned_questions(conn, quiz_id, user_id):
    """Only return quizzes belonging to the signed-in student."""

    owned = conn.execute(
        """
        SELECT q.id
        FROM quizzes q
        JOIN exams e ON e.id = q.exam_id
        WHERE q.id=?
          AND e.telegram_user_id=?
        """,
        (quiz_id, user_id),
    ).fetchone()

    if not owned:
        raise HTTPException(
            status_code=404,
            detail="Quiz not found",
        )

    return conn.execute(
        """
        SELECT * FROM questions
        WHERE quiz_id=?
        ORDER BY id
        """,
        (quiz_id,),
    ).fetchall()


class Answer(BaseModel):
    question_id: int
    option: Literal["A", "B", "C", "D"]


class Submission(BaseModel):
    submission_id: UUID
    answers: list[Answer] = Field(min_length=1, max_length=200)


